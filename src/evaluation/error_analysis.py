COMMAND = "python -m src.evaluation.error_analysis"
KINDS = ("false_negatives", "false_positives")
KIND_LABELS = {"false_negatives": "false negatives", "false_positives": "false positives"}
FLAG_COLUMNS = ("validated_by_human", "second_opinion", "initial_autogenerated_report")


def rank_errors(y: np.ndarray, probs: np.ndarray, classes: Sequence[str], thresholds: Mapping[str, float],
                ecg_ids: np.ndarray, kind: str, n: int) -> list[dict[str, Any]]:
    """The n records with the most confident errors of one kind, most confident first.

    y, probs: (records, classes); thresholds: {class: threshold} for the classes that have one. A record is
    flagged for a class when its probability is >= the threshold. Returns, per record, {"index": row in y,
    "ecg_id", "errors": [{"class", "probability", "threshold"}, ...]} with its errors most confident first.
    """
    if kind not in KINDS:
        raise ValueError(f"kind must be one of {KINDS}, got {kind!r}")
    if n < 1:
        raise ValueError(f"n must be at least 1, got {n}")
    y, probs, ecg_ids = np.asarray(y), np.asarray(probs, dtype=np.float64), np.asarray(ecg_ids)
    if y.shape != probs.shape or y.shape[1] != len(classes) or len(ecg_ids) != len(y):
        raise ValueError(f"y {y.shape}, probs {probs.shape}, {len(classes)} classes and {len(ecg_ids)} ecg_ids disagree")
    unknown = sorted(set(thresholds) - set(classes))
    if unknown:
        raise ValueError(f"Thresholds for unknown classes {unknown}")
    by_record: dict[int, list[tuple[float, dict[str, Any]]]] = {}
    for c, threshold in thresholds.items():
        j = list(classes).index(c)
        flagged = probs[:, j] >= threshold
        wrong = (y[:, j] == 1) & ~flagged if kind == "false_negatives" else (y[:, j] == 0) & flagged
        for i in np.flatnonzero(wrong):
            p = float(probs[i, j])
            key = p if kind == "false_negatives" else -p  # smaller key = more confident mistake
            by_record.setdefault(int(i), []).append((key, {"class": c, "probability": p, "threshold": float(threshold)}))
    ranked = sorted(by_record.items(), key=lambda item: (min(k for k, _ in item[1]), int(ecg_ids[item[0]])))
    return [{"index": i, "ecg_id": int(ecg_ids[i]),
             "errors": [e for _, e in sorted(errs, key=lambda ke: (ke[0], ke[1]["class"]))]}
            for i, errs in ranked[:n]]


def quality_notes(row: pd.Series, columns: Sequence[str]) -> dict[str, str | None]:
    """{column: the affected leads as PTB-XL wrote them, or None when the problem was not noted}."""
    out: dict[str, str | None] = {}
    for col in columns:
        v = row[col]
        text = None if pd.isna(v) else str(v).strip(" ,")
        out[col] = text or None
    return out


def diagnostic_statements(scp_codes: Mapping[str, float], code_to_class: Mapping[str, str],
                          classes: Sequence[str]) -> dict[str, dict[str, float]]:
    """{superclass: {SCP code: likelihood}} of the record's diagnostic statements (classes without any omitted)."""
    out: dict[str, dict[str, float]] = {c: {} for c in classes}
    for code, likelihood in scp_codes.items():
        if code in code_to_class:
            out[code_to_class[code]][code] = float(likelihood)
    return {c: s for c, s in out.items() if s}


def describe(example: dict[str, Any], kind: str, y: np.ndarray, probs: np.ndarray, classes: Sequence[str],
             thresholds: Mapping[str, float], db: pd.DataFrame, code_to_class: Mapping[str, str],
             e: dict[str, Any]) -> dict[str, Any]:
    """One example with the model's view of the record and PTB-XL's annotations of it."""
    i, ecg_id = example["index"], example["ecg_id"]
    row = db.loc[ecg_id]
    scp = parse_scp_codes(row["scp_codes"])
    statements = diagnostic_statements(scp, code_to_class, classes)
    errors = []
    for err in example["errors"]:
        stmts = statements.get(err["class"], {})
        errors.append(err | {"statements": stmts,
                             "max_statement_likelihood": max(stmts.values()) if stmts else None})
    sex = None if pd.isna(row["sex"]) else e["sex_codes"][int(row["sex"])]
    age = None if pd.isna(row["age"]) else float(row["age"])
    return {
        "ecg_id": ecg_id,
        "kind": kind,
        "errors": errors,
        "labels": [c for j, c in enumerate(classes) if y[i, j] == 1],
        "flagged": [c for c in thresholds if probs[i, list(classes).index(c)] >= thresholds[c]],
        "calibrated_probabilities": {c: float(probs[i, j]) for j, c in enumerate(classes)},
        "age": None if age is None or age == e["age_over_89_code"] else age,
        "age_over_89": age == e["age_over_89_code"],
        "sex": sex,
        "scp_codes": {k: float(v) for k, v in scp.items()},
        "diagnostic_statements": statements,
        "quality": quality_notes(row, e["quality_columns"]),
        **{col: bool(row[col]) for col in FLAG_COLUMNS},
        "heart_axis": None if pd.isna(row["heart_axis"]) else str(row["heart_axis"]),
        "report": None if pd.isna(row["report"]) else str(row["report"]),
    }


def max_likelihood_counts(db: pd.DataFrame, ecg_ids: np.ndarray, y: np.ndarray, classes: Sequence[str],
                          code_to_class: Mapping[str, str], cls: str) -> dict[str, int]:
    """Among the records labelled cls: how many have each highest likelihood of a cls statement, {"100.0": n, ...}."""
    j = list(classes).index(cls)
    counts: Counter[float] = Counter()
    for ecg_id in ecg_ids[y[:, j] == 1]:
        stmts = diagnostic_statements(parse_scp_codes(db.loc[int(ecg_id), "scp_codes"]), code_to_class, classes)
        counts[max(stmts[cls].values())] += 1
    return {str(k): counts[k] for k in sorted(counts)}


def base_rates(db: pd.DataFrame, ecg_ids: np.ndarray, y: np.ndarray, classes: Sequence[str], abnormal: Sequence[str],
               code_to_class: Mapping[str, str], e: dict[str, Any]) -> dict[str, Any]:
    """The same annotations over every validation record, for comparison with the examples."""
    rows = db.loc[[int(i) for i in ecg_ids]]
    notes = [quality_notes(r, e["quality_columns"]) for _, r in rows.iterrows()]
    return {
        "records": int(len(ecg_ids)),
        "quality_noted": {col: int(sum(n[col] is not None for n in notes)) for col in e["quality_columns"]},
        "any_quality_noted": int(sum(any(v is not None for v in n.values()) for n in notes)),
        **{col: int(rows[col].astype(bool).sum()) for col in FLAG_COLUMNS},
        "mean_labels": float(y.sum(axis=1).mean()),
        "label_counts": {c: int(y[:, j].sum()) for j, c in enumerate(classes)},
        "max_statement_likelihood": {c: max_likelihood_counts(db, ecg_ids, y, classes, code_to_class, c)
                                     for c in abnormal},
    }


def error_rates(db: pd.DataFrame, ecg_ids: np.ndarray, y: np.ndarray, probs: np.ndarray, classes: Sequence[str],
                thresholds: Mapping[str, float], code_to_class: Mapping[str, str]) -> dict[str, Any]:
    """Whether a pattern seen in the examples holds over every validation record, per class with a threshold.

    miss_by_statement: among the class's positives that carry each of its SCP statements, how many are missed.
    miss_by_max_likelihood: the same, grouped by the highest likelihood of the class's statements in the record.
    false_alarm_by_other_label: among the class's negatives that carry each other superclass, how many are flagged.
    A record with several statements or labels counts in each of its groups.
    """
    statements = [diagnostic_statements(parse_scp_codes(db.loc[int(i), "scp_codes"]), code_to_class, classes)
                  for i in ecg_ids]
    out: dict[str, Any] = {"miss_by_statement": {}, "miss_by_max_likelihood": {}, "false_alarm_by_other_label": {}}
    for c, threshold in thresholds.items():
        j = list(classes).index(c)
        flagged = probs[:, j] >= threshold
        by_code: dict[str, list[int]] = {}
        by_lik: dict[float, list[int]] = {}
        for i in np.flatnonzero(y[:, j] == 1):
            missed = int(not flagged[i])
            for code in statements[i][c]:
                by_code.setdefault(code, [0, 0])
                by_code[code][0] += 1
                by_code[code][1] += missed
            lik = max(statements[i][c].values())
            by_lik.setdefault(lik, [0, 0])
            by_lik[lik][0] += 1
            by_lik[lik][1] += missed
        out["miss_by_statement"][c] = {k: {"positives": v[0], "missed": v[1]}
                                       for k, v in sorted(by_code.items(), key=lambda kv: -kv[1][0])}
        out["miss_by_max_likelihood"][c] = {str(k): {"positives": v[0], "missed": v[1]} for k, v in sorted(by_lik.items())}
        negatives = y[:, j] == 0
        out["false_alarm_by_other_label"][c] = {
            o: {"negatives": int((negatives & (y[:, k] == 1)).sum()),
                "flagged": int((negatives & (y[:, k] == 1) & flagged).sum())}
            for k, o in enumerate(classes) if o != c}
        out["false_alarm_by_other_label"][c]["all negatives"] = {"negatives": int(negatives.sum()),
                                                                  "flagged": int((negatives & flagged).sum())}
    return out


def summarise(examples: list[dict[str, Any]], quality_columns: Sequence[str]) -> dict[str, Any]:
    """Counts over one kind's examples, the same quantities as base_rates."""
    return {
        "records": len(examples),
        "error_classes": dict(Counter(ex["errors"][0]["class"] for ex in examples)),
        "quality_noted": {col: sum(ex["quality"][col] is not None for ex in examples) for col in quality_columns},
        "any_quality_noted": sum(any(v is not None for v in ex["quality"].values()) for ex in examples),
        **{col: sum(ex[col] for ex in examples) for col in FLAG_COLUMNS},
        "mean_labels": float(np.mean([len(ex["labels"]) for ex in examples])),
        "label_counts": dict(Counter(c for ex in examples for c in ex["labels"])),
        "max_statement_likelihood_of_error_class": [ex["errors"][0]["max_statement_likelihood"] for ex in examples],
    }


def _short(ex: dict[str, Any]) -> tuple[str, str]:
    """Heading and note drawn above one example's panel."""
    err = ex["errors"][0]
    verb = "missed" if ex["kind"] == "false_negatives" else "flagged"
    sign = "<" if ex["kind"] == "false_negatives" else "≥"
    others = "".join(f"; also {o['class']} {o['probability']:.3f}" for o in ex["errors"][1:])
    heading = (f"ecg_id {ex['ecg_id']}: {err['class']} {verb}, p {err['probability']:.3f} {sign} threshold "
               f"{err['threshold']:.3f}{others}")
    stmts = ", ".join(f"{code} {lik:g}" for s in ex["diagnostic_statements"].values() for code, lik in s.items())
    quality = ", ".join(f"{k.replace('_', ' ')} ({v})" for k, v in ex["quality"].items() if v) or "none noted"
    age = "over 89 y" if ex["age_over_89"] else "age ?" if ex["age"] is None else f"{ex['age']:g} y"
    note = (f"Labels {'/'.join(ex['labels']) or '-'}; flagged {'/'.join(ex['flagged']) or '-'}. "
            f"{age}, {ex['sex'] or 'sex ?'}. Diagnostic statements (likelihood): {stmts}. Quality: {quality}.")
    return heading, note


def error_analysis(cfg: dict[str, Any]) -> dict[str, Any]:
    """Rank, describe and plot both kinds of error. Returns the report (written by main)."""
    e = cfg["error_analysis"]
    git = git_state()
    manifest = load_release(cfg)
    preds = release_validation_predictions(cfg, manifest)
    run, classes = preds.run, preds.run["classes"]
    calibration = load_calibration(calibration_path(cfg), run, classes, ecg_id_digest(preds.ecg_ids))
    probs = calibrated_probabilities(preds.logits, calibration["calibrators"], classes)
    thresholds_report = read_json(thresholds_path(cfg))
    point = e["operating_point"]
    thresholds = thresholds_report["operating_points"][point]["thresholds"]
    abnormal = abnormal_classes(classes, cfg["evaluation"]["normal_class"])
    if sorted(thresholds) != sorted(abnormal) and point == "high_sensitivity":
        raise ValueError(f"The high-sensitivity thresholds cover {sorted(thresholds)}, expected {abnormal}")
    y = np.asarray(preds.targets).astype(np.int64)
    scored = operating_point_metrics(y, probs, classes, thresholds)

    ds = cfg["dataset"]
    raw_dir = project_path(cfg["paths"]["raw_dir"])
    db = read_database(raw_dir, ds["database_csv"])
    code_to_class = diagnostic_map(read_statements(raw_dir, ds["statements_csv"]), list(classes))
    cache = open_cache(run["config"], build_if_missing=False)
    rows = cache.rows("val")
    if not np.array_equal(cache.index["ecg_id"].to_numpy()[rows], preds.ecg_ids):
        raise ValueError("The cache's validation rows are not the predicted records, in the same order")

    f, fig_style = e["figures"], cfg["evaluation"]["figures"]
    leads = list(cache.meta["leads"])
    report_examples, figures = {}, {}
    for kind in KINDS:
        ranked = rank_errors(y, probs, classes, thresholds, preds.ecg_ids, kind, e["examples"])
        if len(ranked) < e["examples"]:
            raise ValueError(f"Only {len(ranked)} records have {KIND_LABELS[kind]}, {e['examples']} were asked for")
        examples = [describe(ex, kind, y, probs, classes, thresholds, db, code_to_class, e) for ex in ranked]
        for rank, ex in enumerate(examples, start=1):
            ex["rank"] = rank
        report_examples[kind] = examples
        headings, notes = zip(*(_short(ex) for ex in examples))
        headings = [f"#{ex['rank']}  {h}" for ex, h in zip(examples, headings)]
        signals = np.stack([cache.signals[rows[ex["index"]]] for ex in ranked])
        order = "lowest" if kind == "false_negatives" else "highest"
        figures[kind] = plots.plot_ecg_examples(
            signals, leads, ds["sampling_rate_hz"], headings, notes,
            project_path(cfg["paths"]["figures_dir"]) / f[kind],
            title=f"The {e['examples']} most confident {KIND_LABELS[kind]} on the validation split "
                  f"({point.replace('_', '-')} operating point)",
            subtitle=f"Fold 9, model {run['run_id']} (release v{manifest['model_version']}). Ranked by calibrated "
                     f"probability of the class, {order} first; one panel per record. Raw signal in mV, 12 leads "
                     f"stacked {f['lead_spacing_mv']:g} mV apart on one scale.",
            columns=f["columns"], panel_in=f["panel_in"], lead_spacing_mv=f["lead_spacing_mv"],
            time_grid_s=f["time_grid_s"], dpi=fig_style["dpi"])

    return {
        "description": "Most confident false negatives and false positives of the release model on the validation "
                       f"split, at the {point} operating point, with PTB-XL's annotations of each record and the same "
                       "annotations over all validation records. The thresholds were chosen on these records.",
        "generated_by": " ".join([COMMAND, *sys.argv[1:]]),
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "git": git,
        "split": "val",
        "records": int(len(y)),
        "patients": int(len(np.unique(preds.patient_ids))),
        "classes": classes,
        "model": {"version": manifest["model_version"], "run_id": run["run_id"],
                  "checkpoint": manifest["release_checkpoint"]["path"],
                  "sha256": manifest["release_checkpoint"]["sha256"]},
        "calibration": {"file": repo_path(calibration_path(cfg)), "sha256": calibration["sha256"]},
        "operating_point": point,
        "thresholds": thresholds,
        "ranking_rule": "per record, its most confident error of the kind: lowest calibrated probability of a present "
                        "class (false negatives), highest of an absent class (false positives); ties to the lower ecg_id",
        "errors_at_operating_point": {c: {"fn": scored["per_class"][c]["fn"], "fp": scored["per_class"][c]["fp"],
                                          "positives": int(y[:, classes.index(c)].sum())} for c in thresholds},
        "examples": report_examples,
        "summary": {kind: summarise(report_examples[kind], e["quality_columns"]) for kind in KINDS},
        "validation_base_rates": base_rates(db, preds.ecg_ids, y, classes, abnormal, code_to_class, e),
        "validation_error_rates": error_rates(db, preds.ecg_ids, y, probs, classes, thresholds, code_to_class),
        "figures": {k: repo_path(v) for k, v in figures.items()},
    }


def format_examples(report: dict[str, Any], kind: str) -> str:
    """A markdown table of one kind's examples."""
    lines = ["| # | ecg_id | Error (p vs threshold) | Labels | Flagged | Age, sex | Diagnostic statements "
             "(likelihood) | Quality notes |",
             "|---|---|---|---|---|---|---|---|"]
    for ex in report["examples"][kind]:
        errs = "; ".join(f"{x['class']} {x['probability']:.3f} vs {x['threshold']:.3f}" for x in ex["errors"])
        stmts = ", ".join(f"{code} {lik:g}" for s in ex["diagnostic_statements"].values() for code, lik in s.items())
        quality = "; ".join(f"{k} ({v})" for k, v in ex["quality"].items() if v) or "none"
        age = "over 89" if ex["age_over_89"] else "?" if ex["age"] is None else f"{ex['age']:g}"
        lines.append(f"| {ex['rank']} | {ex['ecg_id']} | {errs} | {', '.join(ex['labels'])} | "
                     f"{', '.join(ex['flagged']) or '-'} | {age}, {ex['sex'] or '?'} | {stmts} | {quality} |")
    return "\n".join(lines)


def format_comparison(report: dict[str, Any]) -> str:
    """A markdown table: annotations among the false negatives, the false positives and all validation records."""
    s, base = report["summary"], report["validation_base_rates"]
    fn, fp = s["false_negatives"], s["false_positives"]
    cols = list(base["quality_noted"])

    def share(k: int, n: int) -> str:
        return f"{k} of {n} ({k / n:.0%})"

    lines = ["| Annotation | False negatives | False positives | All validation records |", "|---|---|---|---|"]
    for col in cols:
        lines.append(f"| {col} noted | {share(fn['quality_noted'][col], fn['records'])} | "
                     f"{share(fp['quality_noted'][col], fp['records'])} | "
                     f"{share(base['quality_noted'][col], base['records'])} |")
    lines.append(f"| any quality note | {share(fn['any_quality_noted'], fn['records'])} | "
                 f"{share(fp['any_quality_noted'], fp['records'])} | {share(base['any_quality_noted'], base['records'])} |")
    for col in FLAG_COLUMNS:
        lines.append(f"| {col} | {share(fn[col], fn['records'])} | {share(fp[col], fp['records'])} | "
                     f"{share(base[col], base['records'])} |")
    lines.append(f"| mean superclass labels per record | {fn['mean_labels']:.2f} | {fp['mean_labels']:.2f} | "
                 f"{base['mean_labels']:.2f} |")
    return "\n".join(lines)


def format_rates(report: dict[str, Any]) -> str:
    """Markdown tables of the miss and false-alarm rates over all validation records."""
    rates = report["validation_error_rates"]

    def pct(k: int, n: int) -> str:
        return f"{k}/{n} ({k / n:.0%})"

    lines = ["Missed positives by the class's SCP statement (statements on at least one positive):", "",
             "| Class | Statement: missed/positives |", "|---|---|"]
    for c, by_code in rates["miss_by_statement"].items():
        lines.append(f"| {c} | " + ", ".join(f"{code} {pct(v['missed'], v['positives'])}" for code, v in by_code.items())
                     + " |")
    lines += ["", "Missed positives by the highest likelihood of the class's statements:", "",
              "| Class | Likelihood: missed/positives |", "|---|---|"]
    for c, by_lik in rates["miss_by_max_likelihood"].items():
        lines.append(f"| {c} | " + ", ".join(f"{float(k):g}: {pct(v['missed'], v['positives'])}"
                                             for k, v in by_lik.items()) + " |")
    columns = [*report["classes"], "all negatives"]
    lines += ["", "Flagged negatives (false alarms), by another label the record carries:", "",
              "| Class | " + " | ".join(f"with {k}" if k in report["classes"] else k for k in columns) + " |",
              "|---|" + "---|" * len(columns)]
    for c, by_label in rates["false_alarm_by_other_label"].items():
        cells = [pct(by_label[k]["flagged"], by_label[k]["negatives"]) if k in by_label and by_label[k]["negatives"]
                 else "-" for k in columns]
        lines.append(f"| {c} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Most confident validation errors of the release model.")
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG_PATH)
    args = parser.parse_args(argv)
    cfg = load_config(args.config)
    report = error_analysis(cfg)
    path = project_path(cfg["paths"]["reports_dir"]) / cfg["error_analysis"]["report_file"]
    write_json(path, report)
    if report["git"]["dirty"]:
        print(f"WARNING: tracked files differ from commit {report['git']['commit'][:7]}; the report records dirty=true.")
    print(f"Validation split: {report['records']:,} records. Release model v{report['model']['version']}, "
          f"{report['operating_point']} operating point.")
    print("Errors at this operating point:", ", ".join(f"{c} {v['fn']} FN / {v['fp']} FP ({v['positives']} positives)"
                                                     for c, v in report["errors_at_operating_point"].items()))
    for kind in KINDS:
        print()
        print(f"Most confident {KIND_LABELS[kind]}:")
        print(format_examples(report, kind))
    print()
    print(format_comparison(report))
    print()
    print(format_rates(report))
    print()
    print("Highest likelihood of the missed class's statements, false negatives:",
          report["summary"]["false_negatives"]["max_statement_likelihood_of_error_class"])
    print("Validation positives by highest statement likelihood:",
          report["validation_base_rates"]["max_statement_likelihood"])
    print()
    for p in [repo_path(path), *report["figures"].values()]:
        print(f"Saved {p}")
