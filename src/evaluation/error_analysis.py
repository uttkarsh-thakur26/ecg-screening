"""The most confident false negatives and false positives of the release model, on the validation split only.

    python -m src.evaluation.error_analysis

PROJECT_SPEC.md section 4: pull the highest-confidence errors, plot them and look for a pattern. Everything here
is fold 9; the test split is never opened.

1. release.pt (checked against reports/release.json) predicts the validation split; the predictions must
   reproduce the run's logged validation metrics. The frozen calibration turns logits into probabilities.
2. At the high-sensitivity operating point (error_analysis.operating_point, thresholds from reports/thresholds.json)
   every (record, abnormal class) pair is a decision. A false negative is a present class below its threshold, a
   false positive an absent class at or above it. NORM has no threshold at this point, so it has no errors here.
3. Confidence is the calibrated probability: the lower it is for a false negative, and the higher for a false
   positive, the more confident the mistake. Errors are grouped by record (its most confident error of the kind
   ranks it; the others are listed with it), and the error_analysis.examples records of each kind are kept.
4. Each example is joined with PTB-XL's own annotations of that record (ptbxl_database.csv): the SCP statements
   with their likelihoods, the signal-quality notes, age and sex, and whether a cardiologist validated the report.
   The same annotations are summarised over all validation records, so the examples can be compared with the
   base rate.
5. reports/error_analysis_val.json holds everything; one figure per kind shows the 12 leads of every example.

The written findings are in reports/error_analysis.md. Because the thresholds were chosen on these same records,
the error counts here are those of the fitted operating point, not an unbiased estimate.
"""

